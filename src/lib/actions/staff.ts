"use server";

import { revalidatePath } from "next/cache";
import { humanizeDbError } from "../errors";
import { z } from "zod";
import bcrypt from "bcryptjs";
import { requireRole } from "../guards";
import { getActiveProperty } from "../auth";
import { query, queryOne, withTransaction } from "../mysql/client";
import { logActivity } from "../activity";
import { STAFF_MODULES } from "../types";

export type ActionState = { ok?: boolean; error?: string };

/** Build the permissions JSON from the staff form's checkboxes. */
function permsFromForm(formData: FormData) {
  return {
    modules: STAFF_MODULES.filter((m) => formData.get(`mod_${m}`) === "on"),
    edit: formData.get("perm_edit") === "on",
    delete: formData.get("perm_delete") === "on",
  };
}

const staffSchema = z.object({
  name: z.string().min(2, "Name is required."),
  phone: z.string().min(8, "Enter a valid phone."),
  email: z.string().email("Enter a valid email."),
  login_password: z.string().min(8, "Password must be 8+ characters."),
});

/** Owner adds a staff member to the active property. Creates a login, a
 *  profile (role 'staff'), and a property_members row — atomically, via a
 *  real transaction (see withTransaction's doc comment for why this is
 *  strictly better than the original's manual-cleanup-on-failure pattern). */
export async function createStaffAction(
  _prev: ActionState,
  formData: FormData,
): Promise<ActionState> {
  await requireRole(["admin"]);
  const pid = await getActiveProperty();
  if (!pid) return { error: "No active property selected." };
  const parsed = staffSchema.safeParse(Object.fromEntries(formData));
  if (!parsed.success) return { error: parsed.error.issues[0]?.message ?? "Check the form." };
  const d = parsed.data;

  const existing = await queryOne<{ id: string }>(`select id from users where email = ?`, [
    d.email.trim().toLowerCase(),
  ]);
  if (existing) return { error: "That email already has a login." };

  const passwordHash = await bcrypt.hash(d.login_password, 10);
  const permissions = JSON.stringify(permsFromForm(formData));

  try {
    await withTransaction(async (tx) => {
      await tx.query(`insert into users (email, password_hash) values (?, ?)`, [
        d.email.trim().toLowerCase(),
        passwordHash,
      ]);
      // MySQL's INSERT doesn't return the row — the id was generated by the
      // column's own DEFAULT (uuid()) at insert time, so fetch it back by
      // the unique email rather than trying to predict/recompute it.
      const created = await tx.queryOne<{ id: string }>(`select id from users where email = ?`, [
        d.email.trim().toLowerCase(),
      ]);
      if (!created) throw new Error("Could not create the staff login.");
      await tx.query(
        `insert into profiles (id, role, pg_id, full_name, phone, permissions) values (?, 'staff', ?, ?, ?, ?)`,
        [created.id, pid, d.name, d.phone, permissions],
      );
      await tx.query(`insert into property_members (property_id, user_id, role) values (?, ?, 'staff')`, [
        pid,
        created.id,
      ]);
    });
  } catch (error) {
    return { error: humanizeDbError(error as never, "Could not create the staff login.") };
  }

  await logActivity("staff.added", `Added staff ${d.name}`);
  revalidatePath("/dashboard/staff");
  return { ok: true };
}

/** Update an existing staff member's privileges (owner only). */
export async function updateStaffPermissionsAction(
  _prev: ActionState,
  formData: FormData,
): Promise<ActionState> {
  await requireRole(["admin"]);
  const pid = await getActiveProperty();
  if (!pid) return { error: "No active property selected." };
  const id = String(formData.get("id"));
  if (!id) return { error: "Missing staff member." };

  // scope: only a staff profile that belongs to this property
  const member = await queryOne<{ user_id: string }>(
    `select user_id from property_members where property_id = ? and user_id = ?`,
    [pid, id],
  );
  if (!member) return { error: "That staff member isn't on this property." };

  await query(`update profiles set permissions = ? where id = ? and role = 'staff'`, [
    JSON.stringify(permsFromForm(formData)),
    id,
  ]);
  await logActivity("staff.permissions", "Updated a staff member's privileges");
  revalidatePath("/dashboard/staff");
  return { ok: true };
}

/** Remove a staff member from the active property. Owners (role 'admin') can't
 *  be removed this way. */
export async function deleteStaffAction(formData: FormData): Promise<void> {
  await requireRole(["admin"]);
  const pid = await getActiveProperty();
  if (!pid) return;
  const userId = String(formData.get("id"));

  const profile = await queryOne<{ role: string }>(`select role from profiles where id = ?`, [userId]);
  if (!profile || profile.role !== "staff") return; // never delete owners/admins

  await query(`delete from property_members where property_id = ? and user_id = ?`, [pid, userId]);
  // if they belong to no other property, remove the login + profile
  const row = await queryOne<{ n: number }>(
    `select count(*) as n from property_members where user_id = ?`,
    [userId],
  );
  if ((row?.n ?? 0) === 0) {
    await query(`delete from profiles where id = ?`, [userId]);
    await query(`delete from users where id = ?`, [userId]);
  }
  await logActivity("staff.removed", "Removed a staff member");
  revalidatePath("/dashboard/staff");
}
